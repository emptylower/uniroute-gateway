func TestProjectedUsageFreshRevocationAndReadFailuresNeverUseCachedAmount(t *testing.T) {
	for _, state := range []string{"disabled", "deleted", "database-error", "expired", "quota_exhausted", "user-inactive", "user-deleted", "user-cny", "channels", "group"} {
		t.Run(state, func(t *testing.T) {
			repo, client, svc, counted, _, cfg, credential, projection := projectedAuthFixture(t)
			_, err := svc.GetByKey(context.Background(), credential)
			require.NoError(t, err)
			code := http.StatusUnauthorized
			switch state {
			case "deleted":
				_, err = client.APIKey.UpdateOneID(projection.GatewayAPIKeyID).SetDeletedAt(time.Now()).Save(context.Background())
			case "database-error":
				counted.readError = fmt.Errorf("database unavailable")
				code = http.StatusServiceUnavailable
			case "user-inactive":
				_, err = client.User.UpdateOneID(projection.GatewayUserID).SetStatus("disabled").Save(context.Background())
			case "user-deleted":
				_, err = client.User.UpdateOneID(projection.GatewayUserID).SetDeletedAt(time.Now()).Save(context.Background())
			case "user-cny":
				_, err = repo.sql.ExecContext(context.Background(), `UPDATE users SET billing_currency='CNY' WHERE id=?`, projection.GatewayUserID)
				code = http.StatusForbidden
			case "channels":
				_, err = repo.sql.ExecContext(context.Background(), `INSERT INTO api_key_channels(api_key_id,channel_id) VALUES(?,?)`, projection.GatewayAPIKeyID, 99)
				code = http.StatusForbidden
			case "group":
				g, groupErr := client.Group.Create().SetName("assigned").SetPlatform(service.PlatformOpenAI).SetStatus(service.StatusActive).Save(context.Background())
				require.NoError(t, groupErr)
				_, err = client.APIKey.UpdateOneID(projection.GatewayAPIKeyID).SetGroupID(g.ID).Save(context.Background())
				code = http.StatusForbidden
			default:
				update := client.APIKey.UpdateOneID(projection.GatewayAPIKeyID).SetStatus(state)
				if state == "expired" {
					update.SetExpiresAt(time.Now().Add(-time.Hour))
				}
				if state == "quota_exhausted" {
					update.SetQuotaUsed(1)
				}
				_, err = update.Save(context.Background())
				if state == "expired" || state == "quota_exhausted" {
					code = http.StatusOK
				}
			}
			require.NoError(t, err)
			w := projectedUsageRequest(projectedUsageRouter(client, svc, cfg, &projectedUsageStats{}), credential, "")
			require.Equal(t, code, w.Code, w.Body.String())
			if state == "quota_exhausted" {
				var result struct {
					Quota struct{ Used, Remaining float64 } `json:"quota"`
				}
				require.NoError(t, json.Unmarshal(w.Body.Bytes(), &result))
				require.Equal(t, 1.0, result.Quota.Used)
				require.Zero(t, result.Quota.Remaining)
			}
		})
	}
}

