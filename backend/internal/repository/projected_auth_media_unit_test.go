type projectedAuthJSONCache struct {
	service.APIKeyCache
	entries map[string][]byte
}

func (c *projectedAuthJSONCache) GetAuthCache(_ context.Context, key string) (*service.APIKeyAuthCacheEntry, error) {
	entry := &service.APIKeyAuthCacheEntry{}
	if raw, ok := c.entries[key]; ok {
		return entry, json.Unmarshal(raw, entry)
	}
	return nil, fmt.Errorf("cache miss")
}
func (c *projectedAuthJSONCache) SetAuthCache(_ context.Context, key string, entry *service.APIKeyAuthCacheEntry, _ time.Duration) error {
	raw, err := json.Marshal(entry)
	c.entries[key] = raw
	return err
}
func (c *projectedAuthJSONCache) DeleteAuthCache(_ context.Context, key string) error {
	delete(c.entries, key)
	return nil
}
func (c *projectedAuthJSONCache) PublishAuthCacheInvalidation(context.Context, string) error {
	return nil
}

type projectedAuthCountingRepo struct {
	service.APIKeyRepository
	lookups   int
	readError error
}

func (r *projectedAuthCountingRepo) GetByKeyForAuth(ctx context.Context, key string) (*service.APIKey, error) {
	r.lookups++
	return r.APIKeyRepository.GetByKeyForAuth(ctx, key)
}

func (r *projectedAuthCountingRepo) GetUsageReadState(ctx context.Context, id, userID int64) (*service.APIKey, error) {
	if r.readError != nil {
		return nil, r.readError
	}
	reader, ok := r.APIKeyRepository.(interface {
		GetUsageReadState(context.Context, int64, int64) (*service.APIKey, error)
	})
	if !ok {
		return nil, fmt.Errorf("usage read repository unavailable")
	}
	return reader.GetUsageReadState(ctx, id, userID)
}

func projectedAuthFixture(t *testing.T, currency ...string) (*apiKeyRepository, *dbent.Client, *service.APIKeyService, *projectedAuthCountingRepo, *projectedAuthJSONCache, *config.Config, string, *service.PlatformAPIKeyProjection) {
	t.Helper()
	ctx := context.Background()
	repo, client := newAPIKeyRepoSQLite(t)
	// Migration 191 owns this SQL join; it is not generated by Ent's schema.
	_, schemaErr := repo.sql.ExecContext(ctx, `CREATE TABLE IF NOT EXISTS api_key_channels(api_key_id bigint NOT NULL, channel_id bigint NOT NULL, PRIMARY KEY(api_key_id,channel_id))`)
	require.NoError(t, schemaErr)
	stored := "USD"
	if len(currency) > 0 {
		stored = currency[0]
	}
	u, err := client.User.Create().SetEmail("projected-auth-media@test.com").SetPasswordHash("unit-only").SetRole(service.RoleUser).SetStatus(service.StatusActive).SetPlatformUserID("platform-auth-user").SetBillingCurrency(stored).Save(ctx)
	require.NoError(t, err)
	credential := "sk-unit-projected-auth-media"
	digest := sha256.Sum256([]byte(credential))
	projection := &service.PlatformAPIKeyProjection{GatewayUserID: u.ID, PlatformKeyID: "platform-auth-key", KeySHA256: hex.EncodeToString(digest[:]), KeyPrefix: "sk-unit", Name: "Projected", Status: service.StatusActive, Version: 1}
	require.NoError(t, NewPlatformAPIKeyRepository(client).CreateProjected(ctx, projection, "platform:auth-unit-placeholder"))
	_, err = client.APIKey.UpdateOneID(projection.GatewayAPIKeyID).SetQuota(1).SetQuotaUsed(0.2).Save(ctx)
	require.NoError(t, err)
	cfg := &config.Config{}
	cfg.APIKeyAuth.L2TTLSeconds = 300
	cfg.CanonicalWallet.Mode = config.CanonicalWalletModeEnforce
	cfg.CanonicalWallet.USDWalletEnabled = true
	cfg.CanonicalWallet.USDPolicyVersion = config.CanonicalUSDWalletPolicyVersion
	cache := &projectedAuthJSONCache{entries: map[string][]byte{}}
	counted := &projectedAuthCountingRepo{APIKeyRepository: repo}
	svc := service.NewAPIKeyService(counted, nil, nil, nil, nil, cache, cfg)
	return repo, client, svc, counted, cache, cfg, credential, projection
}

