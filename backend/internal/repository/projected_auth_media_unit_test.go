func TestProjectedAuthOldV21L2RefetchesRealRepository(t *testing.T) {
	_, _, svc, counted, cache, _, credential, projection := projectedAuthFixture(t)
	digest := sha256.Sum256([]byte(credential))
	cache.entries[hex.EncodeToString(digest[:])] = []byte(fmt.Sprintf(`{"snapshot":{"version":21,"api_key_id":%d,"user_id":%d,"routing_mode":"auto_channels","status":"active","quota":0,"quota_used":0,"user":{"id":%d,"platform_user_id":"platform-auth-user","status":"active","billing_currency":"USD"}}}`, projection.GatewayAPIKeyID, projection.GatewayUserID, projection.GatewayUserID))
	key, err := svc.GetByKey(context.Background(), credential)
	require.NoError(t, err)
	require.Equal(t, 1, counted.lookups, "old snapshot must load current DB identity and quota")
	require.NotNil(t, key.PlatformKeyID)
	require.Equal(t, projection.PlatformKeyID, *key.PlatformKeyID)
	require.Equal(t, 1.0, key.Quota)
	key, err = svc.GetByKey(context.Background(), credential)
	require.NoError(t, err)
	require.Equal(t, 1, counted.lookups)
	require.NotNil(t, key.PlatformKeyID)
}

