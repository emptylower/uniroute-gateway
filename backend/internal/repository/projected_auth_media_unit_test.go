func projectedUsageRouter(client *dbent.Client, keys *service.APIKeyService, cfg *config.Config, stats *projectedUsageStats) *gin.Engine {
	gin.SetMode(gin.TestMode)
	settings := service.NewSettingService(NewSettingRepository(client), cfg)
	usage := service.NewUsageService(stats, nil, nil, nil)
	h := handler.NewGatewayHandler(nil, nil, nil, nil, nil, nil, nil, usage, keys, nil, nil, nil, nil, cfg, settings)
	router := gin.New()
	router.Use(gin.HandlerFunc(middleware.NewAPIKeyAuthMiddleware(keys, nil, cfg)))
	router.Use(middleware.RequireGroupAssignment(settings, cfg, middleware.AnthropicErrorWriter))
	router.GET("/v1/usage", h.Usage)
	return router
}

func projectedUsageRequest(router *gin.Engine, credential, query string) *httptest.ResponseRecorder {
	r := httptest.NewRequest(http.MethodGet, "/v1/usage"+query, nil)
	r.Header.Set("Authorization", "Bearer "+credential)
	w := httptest.NewRecorder()
	router.ServeHTTP(w, r)
	return w
}

func TestProjectedUsageFreshOwnQuotaWithWarmAuthAndActualHandler(t *testing.T) {
	_, client, svc, counted, _, cfg, credential, projection := projectedAuthFixture(t)
	ctx := context.Background()
	warm, err := svc.GetByKey(ctx, credential)
	require.NoError(t, err)
	require.Equal(t, 0.2, warm.QuotaUsed)
	_, err = client.APIKey.UpdateOneID(projection.GatewayAPIKeyID).SetQuotaUsed(0.37).Save(ctx)
	require.NoError(t, err)
	stats := &projectedUsageStats{}
	router := projectedUsageRouter(client, svc, cfg, stats)
	w := projectedUsageRequest(router, credential, "?api_key_id=999&user_id=999")
	require.Equal(t, http.StatusOK, w.Code, w.Body.String())
	var data struct {
		Mode  string `json:"mode"`
		Quota struct {
			Unit                   string `json:"unit"`
			Limit, Used, Remaining float64
		} `json:"quota"`
	}
	require.NoError(t, json.Unmarshal(w.Body.Bytes(), &data))
	require.Equal(t, "quota_limited", data.Mode)
	require.Equal(t, "USD", data.Quota.Unit)
	require.Equal(t, 1.0, data.Quota.Limit)
	require.Equal(t, 0.37, data.Quota.Used)
	require.InDelta(t, 0.63, data.Quota.Remaining, 1e-12)
	require.Equal(t, []int64{projection.GatewayAPIKeyID, projection.GatewayAPIKeyID, projection.GatewayAPIKeyID}, stats.keyIDs)
	require.Equal(t, []int64{projection.GatewayUserID}, stats.userIDs)
	stillCached, err := svc.GetByKey(ctx, credential)
	require.NoError(t, err)
	require.Equal(t, 0.2, stillCached.QuotaUsed, "refresh must only alter request-local copy")
	require.Equal(t, 1, counted.lookups)
}

